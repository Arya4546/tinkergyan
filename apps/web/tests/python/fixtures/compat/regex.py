import re
print(re.findall(r"\d+", "a1b22c333"))
print(re.findall(r"(\w)(\d)", "a1 b2 c"))
print(re.findall(r"(\w)=(\d)?", "a=1 b= c=3"))
m = re.search(r"(\d+)-(\d+)", "ab 12-34 x")
print(m.group(0), m.group(1), m.group(1, 2), m.groups(), m.start(), m.end(), m.span(), m.span(2), m[2])
print(re.split(r",\s*", "a, b,c,   d"))
print(re.split(r"(,)", "a,b"))
print(re.split(r",", "a,b,c,d", maxsplit=2))
print(re.search(r"a{2,3}", "caaaat").group())
