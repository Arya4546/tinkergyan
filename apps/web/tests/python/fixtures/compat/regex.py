print(re.search(r"x{2}", "xxx").span())
print(re.findall(r"\bcat\b", "cat concat cat."))
print(re.search(r"hello", "Say HELLO", re.I).group())
print(re.findall(r"^\w+", "one\ntwo\nthree", re.M))
print(re.findall(r"^\w+", "one\ntwo"))
print(re.search(r"a.b", "a\nb"), re.search(r"a.b", "a\nb", re.S).group() == "a\nb")
m = re.search(r"(?P<year>\d{4})-(?P<month>\d\d)", "on 2026-11-28")
print(m.group("year"), m["month"], m.groupdict(), m.lastgroup, m.lastindex)
print(re.sub(r"(?P<w>\w+)@(\w+)", r"\2 at \g<w>", "me@site you@web"))
print(re.sub(r"\s+", "-", "a  b   c", count=1))
print(re.subn(r"o", "0", "foo boo"))
print(re.sub(r"(\d)", lambda m: str(int(m.group(1)) * 2), "a1b2c3"))
print(re.sub("x*", "-", "abxd"))
print(re.findall(r"x*", "axxb"))
print(re.split(r"\b", "hi there"))
print(re.fullmatch(r"\d+", "123"), re.fullmatch(r"\d+", "123a"))
print(re.match(r"\d", "a1"), re.match(r"a", "a1").group())
print(bool(re.match(r"^[\w.+-]+@[\w-]+\.[\w.]+$", "john.doe+x@mail.co.in")))
print(re.escape("a.b*c?"), re.findall(re.escape("1+1"), "1+1=2 1+1"))
p = re.compile(r"(\d+)")
print(p.pattern, p.groups, p.findall("x1y22"), [m.group() for m in p.finditer("7 88 999")])
print(p.search("abc 42", 4).group(), p.match("abc 42", 4).group(), p.search("12345", 0, 3).group())
print(re.findall(r"[^aeiou\s]+", "hello world"))
print(re.findall(r"[]a]", "a]b"))
print(re.findall(r"\$\d+(?:\.\d\d)?", "cost $5 or $12.50"))
print(re.findall(r"(?i)hello", "Hello HELLO"))
print(re.findall(r"""\d+  # digits
                    \s*  # space""", "12 34", re.X))
print(re.findall(r"(a)(b)?", "ab a"))
print(re.search(r"colou?r", "my color").group(), re.search(r"\Aab", "ab").group(), re.search(r"b\Z", "ab").group())
print(re.search(r"end$", "the end\n").group())
print(re.findall(r"{name}", "hi {name}!"))
print(re.findall(r"\w+", "naïve café 😀 x"))
